#!/usr/bin/env python3
"""XMB art from the user's ISO: ICON0 (144x80, also the savedata icon) and
PIC1 (480x272). Reads only the three AFS02 entries it needs. Usage:

  xmb_art.py ISO OUTDIR      writes OUTDIR/ICON0.PNG, PIC1.PNG, psp_icon0.h

ICON0: DM13TEX #1 scaled to 144x144, centre-cropped to 144x80; on top,
       DM0ATEX #1 cut to its top 77 rows, scaled to 133x80, centred.
PIC1:  GAL39.TM2 trimmed of transparent rows (512x384), scaled to 480x360,
       top 272 rows kept.
"""
import os, sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'port', 'tools', 'convert'))
from iso import Iso
from afs import Afs
import png, tim2, textures


class Img:
    def __init__(self, w, h, px=None):  # px: list of [r,g,b,a] floats, premultiplied
        self.w, self.h = w, h
        self.px = px if px is not None else [[0.0] * 4 for _ in range(w * h)]

    @classmethod
    def from_pic(cls, p):
        rgba = p['rgba']
        px = []
        for i in range(0, len(rgba), 4):
            a = rgba[i + 3] / 255.0
            px.append([rgba[i] * a, rgba[i + 1] * a, rgba[i + 2] * a, a * 255.0])
        return cls(p['w'], p['h'], px)

    def crop(self, x, y, w, h):
        return Img(w, h, [list(self.px[(y + j) * self.w + x + i]) for j in range(h) for i in range(w)])

    def resize(self, w, h):
        return self._axis(w, True)._axis(h, False)

    def _axis(self, n, horiz):
        """Triangle filter, widened when shrinking (PIL BILINEAR style)."""
        src = self.w if horiz else self.h
        scale = src / n
        sup = max(scale, 1.0)
        taps = []
        for o in range(n):
            c = (o + 0.5) * scale
            lo, hi = max(0, int(c - sup)), min(src, int(c + sup) + 1)
            ws = [(k, max(0.0, 1 - abs((k + 0.5 - c) / sup))) for k in range(lo, hi)]
            t = sum(wt for _, wt in ws) or 1.0
            taps.append([(k, wt / t) for k, wt in ws if wt])
        ow, oh = (n, self.h) if horiz else (self.w, n)
        out = Img(ow, oh)
        for y in range(oh):
            for x in range(ow):
                acc = out.px[y * ow + x]
                for k, wt in taps[x if horiz else y]:
                    s = self.px[y * self.w + k] if horiz else self.px[k * self.w + x]
                    for c in range(4):
                        acc[c] += s[c] * wt
        return out

    def over(self, top, x0, y0):
        for j in range(top.h):
            for i in range(top.w):
                s, d = top.px[j * top.w + i], self.px[(y0 + j) * self.w + x0 + i]
                k = 1 - s[3] / 255.0
                for c in range(4):
                    d[c] = s[c] + d[c] * k

    def rgba(self):
        out = bytearray()
        for r, g, b, a in self.px:
            f = 255.0 / a if a > 0 else 0
            out += bytes(min(255, max(0, round(v))) for v in (r * f, g * f, b * f, a))
        return out


def pack_pic(a, name, idx):
    d, _ = textures.decode_pack(a.read(a.find(name)))
    _, _, _, off, _ = textures.records(d)[idx]
    return Img.from_pic(tim2.parse(d, off)[0])


def main():
    iso_path, outdir = sys.argv[1], sys.argv[2]
    os.makedirs(outdir, exist_ok=True)
    a = Afs(Iso(iso_path), 2)

    icon = pack_pic(a, 'DM13TEX.BIN', 1).resize(144, 144).crop(0, 32, 144, 80)
    logo = pack_pic(a, 'DM0ATEX.BIN', 1)
    logo = logo.crop(0, 0, logo.w, 77).resize(133, 80)
    icon.over(logo, (144 - 133) // 2, 0)

    gal = Img.from_pic(tim2.parse(a.read(a.find('GAL39.TM2')))[0])
    rows = [y for y in range(gal.h) if any(gal.px[y * gal.w + x][3] > 0 for x in range(gal.w))]
    gal = gal.crop(0, rows[0], gal.w, rows[-1] - rows[0] + 1)
    pic1 = gal.resize(480, 360).crop(0, 0, 480, 272)

    icon0 = os.path.join(outdir, 'ICON0.PNG')
    png.write_rgba(icon0, 144, 80, icon.rgba())
    png.write_rgba(os.path.join(outdir, 'PIC1.PNG'), 480, 272, pic1.rgba())
    data = open(icon0, 'rb').read()
    with open(os.path.join(outdir, 'psp_icon0.h'), 'w') as f:
        f.write('/* generated by port/psp/tools/xmb_art.py */\n'
                'static const unsigned char psp_icon0[%d] = {%s};\n'
                % (len(data), ','.join(str(b) for b in data)))
    print('ICON0 144x80, PIC1 480x272 (GAL39 trimmed %dx%d) -> %s' % (gal.w, gal.h, outdir))


if __name__ == '__main__':
    main()
