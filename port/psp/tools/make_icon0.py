#!/usr/bin/env python3
"""ICON0.PNG for the PSP savedata list (P59): 144x80, an original plain
design (dark gradient, "MvC2" in a block font). No game art. Usage:
make_icon0.py out.png | out.h (C array psp_icon0[])"""
import struct, sys, zlib

W, H = 144, 80
FONT = {  # 5x7
    'M': ["10001", "11011", "10101", "10001", "10001", "10001", "10001"],
    'v': ["00000", "00000", "10001", "10001", "10001", "01010", "00100"],
    'C': ["01111", "10000", "10000", "10000", "10000", "10000", "01111"],
    '2': ["01110", "10001", "00001", "00110", "01000", "10000", "11111"],
}
px = [[(20 + y, 10 + y // 2, 60 + y) for x in range(W)] for y in range(H)]
text, s = "MvC2", 5
tw = len(text) * 6 * s - s
x0, y0 = (W - tw) // 2, (H - 7 * s) // 2
for i, ch in enumerate(text):
    for r, row in enumerate(FONT[ch]):
        for c, bit in enumerate(row):
            if bit == '1':
                for dy in range(s):
                    for dx in range(s):
                        px[y0 + r * s + dy][x0 + (i * 6 + c) * s + dx] = (250, 210, 40)
raw = b"".join(b"\0" + bytes(v for p in row for v in p) for row in px)
def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
if sys.argv[1].endswith(".h"):
    body = ",".join(str(b) for b in png)
    open(sys.argv[1], "w").write("/* generated by port/psp/tools/make_icon0.py */\nstatic const unsigned char psp_icon0[%d] = {%s};\n" % (len(png), body))
else:
    open(sys.argv[1], "wb").write(png)
